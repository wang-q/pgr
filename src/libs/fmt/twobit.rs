    fn random_dna(rng: &mut StdRng, len: usize) -> String {
        let alphabet = *b"ACGTacgtNMRWSYKVHDXnn-*_ 0123456789Uu";
        (0..len)
            .map(|_| alphabet[rng.random_range(0..alphabet.len())] as char)
            .collect()
    }

    #[test]
    fn classify_matches_scalar_random() {
        // AVX2 / wide paths must agree with the scalar reference on every
        // bit of the N/lower masks and every 2-bit code.
        let mut rng = StdRng::seed_from_u64(20260809);
        for len in [0usize, 1, 15, 16, 17, 31, 32, 33, 63, 64, 65, 500, 1000] {
            for _ in 0..10 {
                let dna = random_dna(&mut rng, len);
                for path in [SimdPath::Auto, SimdPath::Wide, SimdPath::Scalar] {
                    let got = classify_dna_with(path, dna.as_bytes());
                    let mut expected = DnaClasses {
                        n_mask: vec![0; got.n_mask.len()],
                        lower_mask: vec![0; got.lower_mask.len()],
                        codes: vec![0; len],
                    };
                    classify_scalar(dna.as_bytes(), &mut expected);
                    assert_eq!(
                        got.n_mask, expected.n_mask,
                        "n_mask len={len} path={path:?}"
                    );
                    assert_eq!(
                        got.lower_mask, expected.lower_mask,
                        "lower len={len} path={path:?}"
                    );
                    assert_eq!(got.codes, expected.codes, "codes len={len} path={path:?}");
                }
            }
        }
    }

    #[test]
    fn from_dna_matches_scalar_reference() {
        // Rebuild from_dna output from the scalar classifier and compare.
        let mut rng = StdRng::seed_from_u64(7);
        for len in [0usize, 1, 4, 5, 16, 17, 100] {
            for _ in 0..20 {
                let dna = random_dna(&mut rng, len);
                for do_mask in [false, true] {
                    let (packed, n_blocks, mask_blocks, size) =
                        Blocks::from_dna(&dna, do_mask).unwrap();
                    let mut classes = DnaClasses {
                        n_mask: vec![0; len.div_ceil(32)],
                        lower_mask: vec![0; len.div_ceil(32)],
                        codes: vec![0; len],
                    };
                    classify_scalar(dna.as_bytes(), &mut classes);
                    let n_ref = blocks_from_mask(&classes.n_mask, len);
                    let mask_ref = if do_mask {
                        blocks_from_mask(&classes.lower_mask, len)
                    } else {
                        Vec::new()
                    };
                    assert_eq!(packed, pack_codes(&classes.codes), "packed len={len}");
                    assert_eq!(n_blocks.0, n_ref, "n_blocks len={len}");
                    assert_eq!(mask_blocks.0, mask_ref, "mask_blocks len={len}");
                    assert_eq!(size, len as u32);
                }
            }
        }
    }

    fn create_v1_2bit_data() -> Vec<u8> {
        let mut data = Vec::new();

        // Header (16 bytes)
        data.extend_from_slice(&TWOBIT_MAGIC.to_le_bytes()); // Magic
        data.extend_from_slice(&1u32.to_le_bytes()); // Version 1
        data.extend_from_slice(&1u32.to_le_bytes()); // SeqCount 1
        data.extend_from_slice(&0u32.to_le_bytes()); // Reserved

        // Index
        // Name: "seq1"
        let name = "seq1";
        data.push(name.len() as u8);
        data.extend_from_slice(name.as_bytes());

        // Offset calculation:
        // Header (16) + NameLen(1) + Name(4) + Offset(8) = 29 bytes
        let offset = 29u64;
        data.extend_from_slice(&offset.to_le_bytes());

        // Data Record at offset 29
        // Sequence: TCAG (4 bp)
        // T=00, C=01, A=10, G=11 -> 00011011 = 0x1B
        let dna_size = 4u32;
        data.extend_from_slice(&dna_size.to_le_bytes());

        // N Blocks
        data.extend_from_slice(&0u32.to_le_bytes()); // Count

        // Mask Blocks
        data.extend_from_slice(&0u32.to_le_bytes()); // Count

        // Reserved
        data.extend_from_slice(&0u32.to_le_bytes());

        // Packed DNA
        data.push(0x1B); // TCAG

        data
    }

    #[test]
    fn test_read_v1_basic() -> Result<()> {
        let data = create_v1_2bit_data();
        let cursor = Cursor::new(data);
        let mut tb = TwoBitFile::new(cursor)?;

        assert_eq!(tb.version, 1);

        let names = tb.get_sequence_names();
        assert_eq!(names, vec!["seq1"]);

        // Read "seq1"
        let seq = tb.read_sequence("seq1", None, None, false)?;
        assert_eq!(seq, "TCAG");

        Ok(())
    }

