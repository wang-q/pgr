/// R `pow1p`: accurate `(1+x)^y` for |x| << 1.
fn pow1p(x: f64, y: f64) -> f64 {
    if y.is_nan() {
        return if x == 0.0 { 1.0 } else { y };
    }
    if 0.0 <= y && y == y.trunc() && y <= 4.0 {
        return match y as i32 {
            0 => 1.0,
            1 => x + 1.0,
            2 => x * (x + 2.0) + 1.0,
            3 => x * (x * (x + 3.0) + 3.0) + 1.0,
            _ => x * (x * (x * (x + 4.0) + 6.0) + 4.0) + 1.0,
        };
    }
    if (x + 1.0) - 1.0 == x || x.abs() > 0.5 || x.is_nan() {
        (1.0 + x).powf(y)
    } else {
        (y * (1.0 + x).ln()).exp()
    }
}

/// R `dbinom_raw(x, n, p, q)`: the binomial density without argument checks.
fn dbinom_raw(x: f64, n: f64, p: f64, q: f64) -> f64 {
    if p == 0.0 {
        return if x == 0.0 { 1.0 } else { 0.0 };
    }
    if q == 0.0 {
        return if x == n { 1.0 } else { 0.0 };
    }
    if x == 0.0 {
        if n == 0.0 {
            return 1.0;
        }
        return if p > q { q.powf(n) } else { pow1p(-p, n) };
    }
    if x == n {
        return if p > q { pow1p(-q, n) } else { p.powf(n) };
    }
    if x < 0.0 || x > n {
        return 0.0;
    }
    let lc = stirlerr(n) - stirlerr(x) - stirlerr(n - x) - bd0(x, n * p) - bd0(n - x, n * q);
    let lf = M_LN_2PI + x.ln() + (1.0 - x / n).ln();
    (lc - 0.5 * lf).exp()
}

