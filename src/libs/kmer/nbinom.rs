/// R `bd0(x, np)`: the binomial deviance, cancellation-free.
fn bd0(x: f64, np: f64) -> f64 {
    if !x.is_finite() || !np.is_finite() || np == 0.0 {
        return f64::NAN;
    }
    if (x - np).abs() < 0.1 * (x + np) {
        let mut v = (x - np) / (x + np);
        let mut s = (x - np) * v;
        if s.abs() < DBL_MIN {
            return s;
        }
        let mut ej = 2.0 * x * v;
        v *= v;
        for j in 1..1000 {
            ej *= v;
            let s_ = s;
            s += ej / ((j << 1) + 1) as f64;
            if s == s_ {
                return s;
            }
        }
    }
    x * (x / np).ln() + np - x
}

/// R `logcf`: continued fraction used by `log1pmx`/`lgamma1p`.
fn logcf(x: f64, i: f64, d: f64, eps: f64) -> f64 {
    let mut c1 = 2.0 * d;
    let mut c2 = i + d;
    let mut c4 = c2 + d;
    let mut a1 = c2;
    let mut b1 = i * (c2 - i * x);
    let b2_init = d * d * x;
    let mut a2 = c4 * c2 - b2_init;
    let mut b2 = c4 * b1 - i * b2_init;

    while (a2 * b1 - a1 * b2).abs() > (eps * b1 * b2).abs() {
        let c3 = c2 * c2 * x;
        c2 += d;
        c4 += d;
        a1 = c4 * a2 - c3 * a1;
        b1 = c4 * b2 - c3 * b1;

        let c3 = c1 * c1 * x;
        c1 += d;
        c4 += d;
        a2 = c4 * a1 - c3 * a2;
        b2 = c4 * b1 - c3 * b2;

        if b2.abs() > SCALEFACTOR {
            a1 /= SCALEFACTOR;
            b1 /= SCALEFACTOR;
            a2 /= SCALEFACTOR;
            b2 /= SCALEFACTOR;
        } else if b2.abs() < 1.0 / SCALEFACTOR {
            a1 *= SCALEFACTOR;
            b1 *= SCALEFACTOR;
            a2 *= SCALEFACTOR;
            b2 *= SCALEFACTOR;
        }
    }
    a2 / b2
}

/// R `log1pmx`: accurate `log(1+x) - x`, particularly for small `x`.
fn log1pmx(x: f64) -> f64 {
    const MIN_LOG1_VALUE: f64 = -0.79149064;
    if !(MIN_LOG1_VALUE..=1.0).contains(&x) {
        return (1.0 + x).ln() - x;
    }
    let r = x / (2.0 + x);
    let y = r * r;
    if x.abs() < 1e-2 {
        const TWO: f64 = 2.0;
        r * ((((TWO / 9.0 * y + TWO / 7.0) * y + TWO / 5.0) * y + TWO / 3.0) * y - x)
    } else {
        const TOL_LOGCF: f64 = 1e-14;
        r * (2.0 * y * logcf(y, 3.0, 2.0, TOL_LOGCF) - x)
    }
}

