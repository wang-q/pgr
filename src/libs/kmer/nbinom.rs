/// R `ebd0`: split `x*log(x/M) + M - x` into a high and low part.
#[allow(clippy::needless_range_loop)]
fn ebd0(x: f64, m: f64) -> (f64, f64) {
    const S: f64 = 1024.0; // 2^10
    const N: i32 = 128;
    let (mut yl, mut yh) = (0.0, 0.0);
    if x == m {
        return (yl, yh);
    }
    if x == 0.0 {
        return (0.0, m);
    }
    if m == 0.0 {
        return (0.0, f64::INFINITY);
    }
    if m / x == f64::INFINITY {
        return (0.0, m);
    }
    let (r, e) = frexp(m / x);
    if M_LN2 * (-e as f64) > 1.0 + DBL_MAX / x {
        return (0.0, f64::INFINITY);
    }
    let i = ((r - 0.5) * (2.0 * N as f64) + 0.5).floor() as usize;
    let f = (S / (0.5 + i as f64 / (2.0 * N as f64)) + 0.5).floor();
    let fg = ldexp(f, -(e + 10));
    if fg == f64::INFINITY {
        return (0.0, fg);
    }
    let add1 = |yh: &mut f64, yl: &mut f64, d: f64| {
        let d1 = (d + 0.5).floor();
        let d2 = d - d1;
        *yh += d1;
        *yl += d2;
    };
    add1(&mut yh, &mut yl, -x * log1pmx((m * fg - x) / x));
    if fg == 1.0 {
        return (yh, yl);
    }
    for j in 0..4 {
        add1(&mut yh, &mut yl, x * BD0_SCALE[i][j] as f64);
        add1(&mut yh, &mut yl, -x * BD0_SCALE[0][j] as f64 * e as f64);
        if !yh.is_finite() {
            return (0.0, f64::INFINITY);
        }
    }
    add1(&mut yh, &mut yl, m);
    add1(&mut yh, &mut yl, -m * fg);
    (yh, yl)
}

/// R `dpois_raw(x, lambda)`: the Poisson density without argument checks.
fn dpois_raw(x: f64, lambda: f64) -> f64 {
    if lambda == 0.0 {
        return if x == 0.0 { 1.0 } else { 0.0 };
    }
    if !lambda.is_finite() {
        return 0.0;
    }
    if x < 0.0 {
        return 0.0;
    }
    if x <= lambda * DBL_MIN {
        return (-lambda).exp();
    }
    if lambda < x * DBL_MIN {
        return (-lambda + x * lambda.ln() - super::genomescope::lgamma(x + 1.0)).exp();
    }
    let (yh, mut yl) = ebd0(x, lambda);
    yl += stirlerr(x);
    let r = M_2PI * x;
    (-yl).exp() * (-yh).exp() / r.sqrt()
}

/// R `dnbinom_mu(x, size, mu)`: negative-binomial density with mean `mu`.
///
/// Mirrors `dnbinom_mu` from `src/nmath/dnbinom.c` (non-log form): `size`
/// successes with mean `mu`, `x` failures; `size = Inf` degenerates to the
/// Poisson density.
pub fn dnbinom(x: f64, size: f64, mu: f64) -> f64 {
    if mu < 0.0 || size < 0.0 {
        return f64::NAN;
    }
    if x < 0.0 || !x.is_finite() {
        return 0.0;
    }
    if x == 0.0 && size == 0.0 {
        return 1.0;
    }
    let x = x.trunc();
    if !size.is_finite() {
        return dpois_raw(x, mu);
    }
    if x == 0.0 {
        return (size
            * if size < mu {
                (size / (size + mu)).ln()
            } else {
                (1.0 - mu / (size + mu)).ln()
            })
        .exp();
    }
    if x < 1e-10 * size {
        let p = if size < mu {
            (size / (1.0 + size / mu)).ln()
        } else {
            (mu / (1.0 + mu / size)).ln()
        };
        return (x * p - mu - lgamma1p(x) + (1.0 + x * (x - 1.0) / (2.0 * size)).ln()).exp();
    }
    let p = size / (size + x);
    let prob = size / (size + mu);
    p * dbinom_raw(size, x + size, prob, 1.0 - prob)
}

#[cfg(test)]
#[allow(clippy::excessive_precision)]
mod tests {
    use super::*;

    #[test]
    fn dnbinom_matches_r_values() {
        // Reference values from R 4.4.2 `dnbinom(x, size, mu)`.
        assert!((dnbinom(45.0, 118.0, 59.0) - 0.01458735683315253).abs() < 1e-14);
        assert!((dnbinom(49.0, 118.0, 59.0) - 0.025931167204568683).abs() < 1e-14);
        assert!((dnbinom(60.0, 118.0, 59.0) - 0.041631643197087231).abs() < 1e-14);
        // x < 1e-10*size branch (MM's formula).
        assert!((dnbinom(12.0, 118.0, 59.0) - 8.1922949898521776e-11).abs() < 1e-20);
        // Poisson limit: dnbinom(x, size=Inf, mu) == dpois(x, mu).
        let poi =
            (-59.0 + 45.0 * 59.0f64.ln() - crate::libs::kmer::genomescope::lgamma(46.0)).exp();
        assert!((dnbinom(45.0, f64::INFINITY, 59.0) - poi).abs() < 1e-12);
        // Small-size edge: x == 0, size == 0 degenerates to a point mass.
        assert_eq!(dnbinom(0.0, 0.0, 5.0), 1.0);
    }
}

