//! R-faithful negative-binomial density (`dnbinom_mu`) and its nmath
//! dependencies (`bd0`/`stirlerr`/`dbinom_raw`/`dpois_raw`), ported from
//! R 4.4.2 `src/nmath/{dnbinom,dbinom,stirlerr,bd0,dpois,pgamma}.c` so the
//! GenomeScope fit reproduces R's cancellation-free numerics.

use std::f64::consts;

const M_LN2: f64 = consts::LN_2;
const M_LN_2PI: f64 = 1.8378770664093454835606594728112;
const M_2PI: f64 = consts::TAU;
const DBL_MAX: f64 = f64::MAX;
const DBL_MIN: f64 = f64::MIN_POSITIVE;
const SCALEFACTOR: f64 = 1.157921e77; // (2^32)^8 = 2^256

/// `frexp`: decompose `x` into mantissa in [0.5, 1) and power of two.
fn frexp(x: f64) -> (f64, i32) {
    if x == 0.0 || !x.is_finite() {
        return (x, 0);
    }
    let bits = x.to_bits();
    let sign = bits & (1u64 << 63);
    let exp = ((bits >> 52) & 0x7ff) as i32;
    let frac = bits & ((1u64 << 52) - 1);
    if exp == 0 {
        // Subnormal: normalize by scaling.
        let mut m = x;
        let mut e = 0i32;
        while m.abs() < 0.5 {
            m *= 2.0;
            e -= 1;
        }
        while m.abs() >= 1.0 {
            m *= 0.5;
            e += 1;
        }
        return (m, e);
    }
    let out_bits = sign | (1022u64 << 52) | frac;
    (f64::from_bits(out_bits), exp - 1022)
}

/// `ldexp`: `f * 2^e`.
fn ldexp(f: f64, e: i32) -> f64 {
    f * 2f64.powi(e)
}

